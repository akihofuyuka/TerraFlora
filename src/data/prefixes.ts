/**
 * 获取地道面向中文用户的词缀显示标签（加成优先）
 */
export function getPrefixOptionLabel(id: number, fallbackName?: string): string {
  if (id === 0) return "无词缀";
  const stats = PREFIX_STATS[id];
  const name = fallbackName || (id === 81 ? "传奇" : id === 84 ? "传奇 (鞭)" : `词缀 #${id}`);
  if (id === 81) return `传奇 (近战: ${stats})`;
  if (id === 84) return `传奇 (${stats})`;
  return stats ? `${name} (${stats})` : name;
}
